"use client";

import { useId, useRef, useState } from "react";
import { ToolColumns, ToolPanel, ToolToolbar } from "@/components/tools/ToolPanel";
import { Alert } from "@/components/ui/Alert";
import { Notice } from "@/components/ui/Notice";
import { Button } from "@/components/ui/Button";
import { CopyButton } from "@/components/ui/CopyButton";
import { Textarea } from "@/components/ui/Field";
import { SegmentedControl } from "@/components/ui/SegmentedControl";
import { downloadText } from "@/lib/download";
import { generateRsaKeyPair, type RsaKeyPair, type RsaKeySize } from "@/lib/tools/rsa";

export function RsaKeyPairGenerator() {
  const [bits, setBits] = useState<RsaKeySize>(2048);
  const [pair, setPair] = useState<RsaKeyPair | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const request = useRef(0);
  const publicId = useId();
  const privateId = useId();

  async function generate() {
    const id = ++request.current;
    setBusy(true);
    setError(null);
    setPair(null);
    const result = await generateRsaKeyPair(bits);
    if (id !== request.current) return;
    setBusy(false);
    if (result.ok) setPair(result);
    else setError(result.error);
  }

  function clear() {
    request.current++;
    setPair(null);
    setError(null);
    setBusy(false);
  }

  return (
    <div className="flex flex-col gap-4">
      <ToolToolbar
        actions={
          <>
            <Button variant="primary" onClick={generate} disabled={busy} aria-busy={busy}>
              {busy ? "Generating…" : pair ? "Generate new pair" : "Generate key pair"}
            </Button>
            <Button variant="ghost" onClick={clear} disabled={!pair && !error}>
              Clear
            </Button>
          </>
        }
      >
        <SegmentedControl
          label="Key size"
          value={String(bits) as "2048" | "4096"}
          onChange={(v) => setBits(Number(v) as RsaKeySize)}
          options={[
            { value: "2048", label: "2048 bits" },
            { value: "4096", label: "4096 bits" },
          ]}
        />
        <p className="max-w-sm pb-1 text-sm text-muted-foreground">
          RSA-OAEP with SHA-256, public exponent 65537. 4096-bit keys can take several seconds to generate.
        </p>
      </ToolToolbar>

      {error ? <Alert title="Could not generate a key pair">{error}</Alert> : null}
      {busy ? <p role="status" className="text-sm text-muted-foreground">Generating a {bits}-bit key pair…</p> : null}
      {pair ? (
        <p role="status" className="font-mono text-xs text-muted-foreground">
          {pair.bits}-bit key pair generated in {(pair.ms / 1000).toFixed(1)} s · Public key SHA-256 fingerprint: {pair.fingerprint}
        </p>
      ) : null}

      <ToolColumns>
        <ToolPanel
          label="Public key (SPKI PEM)"
          htmlFor={publicId}
          actions={
            <>
              <Button size="sm" variant="ghost" disabled={!pair} onClick={() => pair && downloadText("public_key.pem", pair.publicPem, "application/x-pem-file")}>
                Download
              </Button>
              <CopyButton text={pair?.publicPem ?? ""} ariaLabel="Copy public key" />
            </>
          }
          footer="Safe to share: give it to anyone who needs to encrypt data for you."
        >
          <Textarea id={publicId} value={pair?.publicPem ?? ""} readOnly placeholder="-----BEGIN PUBLIC KEY-----" className="min-h-72 bg-subtle text-xs" wrap="off" />
        </ToolPanel>
        <ToolPanel
          label="Private key (PKCS#8 PEM)"
          htmlFor={privateId}
          actions={
            <>
              <Button size="sm" variant="ghost" disabled={!pair} onClick={() => pair && downloadText("private_key.pem", pair.privatePem, "application/x-pem-file")}>
                Download
              </Button>
              <CopyButton text={pair?.privatePem ?? ""} ariaLabel="Copy private key" />
            </>
          }
          footer="Secret: anyone with this key can decrypt data meant for you."
        >
          <Textarea id={privateId} value={pair?.privatePem ?? ""} readOnly placeholder="-----BEGIN PRIVATE KEY-----" className="min-h-72 bg-subtle text-xs" wrap="off" autoComplete="off" />
        </ToolPanel>
      </ToolColumns>

      <Notice title="The private key is sensitive and unencrypted">
        Keys are generated by your browser&apos;s Web Crypto API and exist only in this page&apos;s memory; nothing is sent
        or saved. The exported private key is not password-protected: store it in a secrets manager or encrypt it (for
        example with openssl pkcs8 -topk8 -v2 aes-256-cbc), never commit it to source control, and clear this page when
        you are done. For production systems, generate long-lived keys on the machine that will use them.
      </Notice>
    </div>
  );
}
